// agentTarget describes one harness config file the adapter can write.
type agentTarget struct {
	Kind      agentcfg.Kind `json:"kind"`
	Label     string        `json:"label"`
	Path      string        `json:"path"`
	Exists    bool          `json:"exists"`
	Adapter   bool          `json:"adapter"`
	Mergeable bool          `json:"mergeable"`
	Backup    string        `json:"backup,omitempty"`
}

func homeDir() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return home
}

func dshDefaultPath(home string) string {
	pattern := filepath.Join(home, ".dsh", "profiles", "*", "cordis.patch.yml")
	if matches, err := filepath.Glob(pattern); err == nil && len(matches) > 0 {
		sort.Strings(matches)
		return matches[len(matches)-1]
	}
	return filepath.Join(home, ".dsh", "profiles", "default", "cordis.patch.yml")
}

func defaultAgentTargets() []agentTarget {
	home := homeDir()
	if home == "" {
		return nil
	}
	return []agentTarget{
		{Kind: agentcfg.KindOMP, Label: "omp", Path: filepath.Join(home, ".omp", "agent", "models.yml")},
		{Kind: agentcfg.KindOpenCode, Label: "opencode", Path: filepath.Join(home, ".config", "opencode", "opencode.json"), Mergeable: true},
		{Kind: agentcfg.KindDSH, Label: "DSH", Path: dshDefaultPath(home)},
	}
}

func inspectAgent(path string, target *agentTarget) {
	data, err := os.ReadFile(path)
	if err != nil {
		return
	}
	target.Exists = true
	head := string(data)
	if len(head) > 200 {
		head = head[:200]
	}
	target.Adapter = strings.HasPrefix(strings.TrimSpace(head), "# generated by o2a-v2 agent adapter")
	target.Backup = latestBackup(path)
}

func latestBackup(path string) string {
	matches, _ := filepath.Glob(path + ".bak-*")
	if len(matches) == 0 {
		return ""
	}
	sort.Strings(matches)
	return matches[len(matches)-1]
}

// handleAgents reports the detected harness config files and whether this
// adapter owns them.
func (a *Server) handleAgents(w http.ResponseWriter, _ *http.Request) {
	targets := defaultAgentTargets()
	for index := range targets {
		inspectAgent(targets[index].Path, &targets[index])
	}
	httpx.WriteJSON(w, http.StatusOK, map[string]any{"targets": targets, "models": len(a.manager.AgentModels())})
}

type agentRequest struct {
	Kind    string `json:"kind"`
	Path    string `json:"path"`
	BaseURL string `json:"base_url"`
	Key     string `json:"key"`
	Force   bool   `json:"force"`
}

func (a *Server) agentDocument(input agentRequest) (path string, content []byte, existing []byte, kind agentcfg.Kind, err error) {
	kind = agentcfg.Kind(strings.TrimSpace(input.Kind))
	if kind != agentcfg.KindOMP && kind != agentcfg.KindOpenCode && kind != agentcfg.KindDSH {
		return "", nil, nil, "", errors.New("unknown agent kind")
	}
	path = strings.TrimSpace(input.Path)
	if path == "" {
		for _, target := range defaultAgentTargets() {
			if target.Kind == kind {
				path = target.Path
				break
			}
		}
	}
	if path == "" || !filepath.IsAbs(path) {
		return "", nil, nil, "", errors.New("an absolute config path is required")
	}
	baseURL := strings.TrimSpace(input.BaseURL)
	if baseURL == "" {
		return "", nil, nil, "", errors.New("base_url is required")
	}
	models := a.manager.AgentModels()
	if len(models) == 0 {
		return "", nil, nil, "", errors.New("the model catalog is empty")
	}
	if info, statErr := os.Lstat(path); statErr == nil && info.Mode()&os.ModeSymlink != 0 {
		return "", nil, nil, "", errors.New("refusing to write through a symlink")
	}
	existing, _ = os.ReadFile(path)
	if kind == agentcfg.KindOpenCode {
		content, err = agentcfg.RenderOpenCode(existing, baseURL, strings.TrimSpace(input.Key), models)
	} else {
		var rendered string
		rendered, err = agentcfg.Render(kind, baseURL, strings.TrimSpace(input.Key), models)
		content = []byte(rendered)
	}
	if err != nil {
		return "", nil, nil, "", err
	}
	return path, content, existing, kind, nil
}

// handleAgentPreview renders the file without writing it.
func (a *Server) handleAgentPreview(w http.ResponseWriter, r *http.Request) {
	var input agentRequest
	if err := decodeAdminJSON(w, r, &input); err != nil {
		writeAdminError(w, http.StatusBadRequest, "invalid_request", err.Error())
		return
	}
	path, content, existing, kind, err := a.agentDocument(input)
	if err != nil {
		writeAdminError(w, http.StatusBadRequest, "agent_render_failed", err.Error())
		return
	}
	adapter := strings.HasPrefix(strings.TrimSpace(string(existing)), "# generated by o2a-v2 agent adapter")
	httpx.WriteJSON(w, http.StatusOK, map[string]any{
		"kind": kind, "path": path, "content": string(content), "exists": len(existing) > 0,
		"adapter": adapter || kind == agentcfg.KindOpenCode, "mergeable": kind == agentcfg.KindOpenCode,
	})
}

// handleAgentApply backs up the existing file and writes the rendered one. A
// non-adapter omp/DSH file is refused unless force is set, because replacing it
// could drop another provider or plugin block.
func (a *Server) handleAgentApply(w http.ResponseWriter, r *http.Request) {
	var input agentRequest
	if err := decodeAdminJSON(w, r, &input); err != nil {
		writeAdminError(w, http.StatusBadRequest, "invalid_request", err.Error())
		return
	}
	path, content, existing, kind, err := a.agentDocument(input)
	if err != nil {
		writeAdminError(w, http.StatusBadRequest, "agent_render_failed", err.Error())
		return
	}
	adapter := strings.HasPrefix(strings.TrimSpace(string(existing)), "# generated by o2a-v2 agent adapter")
	if len(existing) > 0 && kind != agentcfg.KindOpenCode && !adapter && !input.Force {
		writeAdminError(w, http.StatusConflict, "not_adapter_owned", "the file exists and was not written by this adapter; send force to replace it")
		return
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		writeAdminError(w, http.StatusInternalServerError, "agent_write_failed", err.Error())
		return
	}
	backup := ""
	if len(existing) > 0 {
		backup = path + ".bak-" + time.Now().Format("20060102-150405")
		if err := os.WriteFile(backup, existing, 0o600); err != nil {
			writeAdminError(w, http.StatusInternalServerError, "agent_write_failed", err.Error())
			return
		}
	}
	if err := os.WriteFile(path, content, 0o600); err != nil {
		writeAdminError(w, http.StatusInternalServerError, "agent_write_failed", err.Error())
		return
	}
	httpx.WriteJSON(w, http.StatusOK, map[string]any{"kind": kind, "path": path, "bytes": len(content), "backup": backup})
}

// handleAgentRestore puts the newest backup of a path back.
func (a *Server) handleAgentRestore(w http.ResponseWriter, r *http.Request) {
	var input struct {
		Path string `json:"path"`
	}
	if err := decodeAdminJSON(w, r, &input); err != nil {
		writeAdminError(w, http.StatusBadRequest, "invalid_request", err.Error())
		return
	}
	path := strings.TrimSpace(input.Path)
	if path == "" || !filepath.IsAbs(path) {
		writeAdminError(w, http.StatusBadRequest, "invalid_request", "an absolute config path is required")
		return
	}
	backup := latestBackup(path)
	if backup == "" {
		writeAdminError(w, http.StatusNotFound, "no_backup", "no backup exists for this path")
		return
	}
	data, err := os.ReadFile(backup)
	if err != nil {
		writeAdminError(w, http.StatusInternalServerError, "agent_restore_failed", err.Error())
		return
	}
	if err := os.WriteFile(path, data, 0o600); err != nil {
		writeAdminError(w, http.StatusInternalServerError, "agent_restore_failed", err.Error())
		return
	}
	httpx.WriteJSON(w, http.StatusOK, map[string]any{"path": path, "restored_from": backup, "bytes": len(data)})
}
