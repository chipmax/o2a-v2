// Package agentcfg renders gateway connection settings for the agent harnesses
// that consume this gateway (omp, opencode, DSH). It only produces text: the
// admin layer owns backups and writes.
package agentcfg

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

// Kind names one supported harness config format.
type Kind string

const (
	KindOMP      Kind = "omp"
	KindOpenCode Kind = "opencode"
	KindDSH      Kind = "dsh"
)

// Model is one catalog model in the shape the harnesses need.
type Model struct {
	ID        string
	Context   int
	Output    int
	Reasoning bool
	Input     []string
}

// Marker prefixes every file this adapter writes, so a later apply can tell an
// adapter-owned file from a hand-written one.
func Marker(kind Kind) string {
	return fmt.Sprintf("# generated by o2a-v2 agent adapter (%s); edits will be replaced", kind)
}

// Render returns the full file content for kinds that are generated, and the
// provider fragment for opencode (which is merged by RenderOpenCode).
func Render(kind Kind, baseURL, key string, models []Model) (string, error) {
	switch kind {
	case KindOMP:
		return renderOMP(baseURL, key, models), nil
	case KindDSH:
		return renderDSH(baseURL, key, models), nil
	case KindOpenCode:
		return renderOpenCodeFragment(baseURL, key, models), nil
	default:
		return "", fmt.Errorf("unsupported agent kind %q", kind)
	}
}

func sorted(models []Model) []Model {
	out := append([]Model(nil), models...)
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

func inputOf(model Model) string {
	inputs := model.Input
	if len(inputs) == 0 {
		inputs = []string{"text"}
	}
	return "[" + strings.Join(inputs, ", ") + "]"
}

func contextOf(model Model) (int, int) {
	context, output := model.Context, model.Output
	if context <= 0 {
		context = 200000
	}
	if output <= 0 {
		output = 32000
	}
	return context, output
}

func renderOMP(baseURL, key string, models []Model) string {
	var b strings.Builder
	b.WriteString(Marker(KindOMP) + "\n")
	b.WriteString("providers:\n  o2a-v2:\n")
	fmt.Fprintf(&b, "    baseUrl: %s\n", baseURL)
	b.WriteString("    api: openai-completions\n")
	if key != "" {
		fmt.Fprintf(&b, "    apiKey: %s\n", key)
	}
	b.WriteString("    models:\n")
	for _, model := range sorted(models) {
		context, output := contextOf(model)
		fmt.Fprintf(&b, "      - id: '%s'\n", model.ID)
		fmt.Fprintf(&b, "        name: '%s'\n", model.ID)
		if model.Reasoning {
			b.WriteString("        reasoning: true\n")
		}
		fmt.Fprintf(&b, "        input: %s\n", inputOf(model))
		fmt.Fprintf(&b, "        contextWindow: %d\n", context)
		fmt.Fprintf(&b, "        maxTokens: %d\n", output)
	}
	return b.String()
}

func renderDSH(baseURL, key string, models []Model) string {
	var b strings.Builder
	b.WriteString(Marker(KindDSH) + "\n")
	b.WriteString("- id: llm-pi-ai\n")
	b.WriteString("  name: \"@deepseek-ai/dsh-llm-pi-ai\"\n")
	b.WriteString("  config:\n    providers:\n      o2a-v2:\n")
	fmt.Fprintf(&b, "        displayName: O2A v2 (%s)\n", baseURL)
	b.WriteString("        api: openai-completions\n")
	fmt.Fprintf(&b, "        baseURL: %s\n", baseURL)
	if key != "" {
		b.WriteString("        headers:\n")
		fmt.Fprintf(&b, "          authorization: Bearer %s\n", key)
	}
	b.WriteString("        models:\n")
	for _, model := range sorted(models) {
		context, output := contextOf(model)
		fmt.Fprintf(&b, "          - id: %s\n", model.ID)
		fmt.Fprintf(&b, "            name: %s\n", model.ID)
		fmt.Fprintf(&b, "            contextWindow: %d\n", context)
		fmt.Fprintf(&b, "            maxTokens: %d\n", output)
		fmt.Fprintf(&b, "            input: %s\n", inputOf(model))
	}
	return b.String()
}

func renderOpenCodeFragment(baseURL, key string, models []Model) string {
	provider := openCodeProvider(baseURL, key, models)
	data, _ := json.MarshalIndent(map[string]any{"provider": map[string]any{"o2a-v2": provider}}, "", "  ")
	return string(data) + "\n"
}

func openCodeProvider(baseURL, key string, models []Model) map[string]any {
	modelMap := make(map[string]any, len(models))
	for _, model := range sorted(models) {
		context, output := contextOf(model)
		input := model.Input
		if len(input) == 0 {
			input = []string{"text"}
		}
		modelMap[model.ID] = map[string]any{
			"name":       model.ID,
			"attachment": hasImage(input),
			"reasoning":  model.Reasoning,
			"tool_call":  true,
			"limit":      map[string]any{"context": context, "output": output},
			"modalities": map[string]any{"input": input, "output": []string{"text"}},
		}
	}
	return map[string]any{
		"name": "O2A v2",
		"npm":  "@ai-sdk/openai-compatible",
		"options": map[string]any{
			"baseURL": baseURL,
			"apiKey":  key,
		},
		"models": modelMap,
	}
}

func hasImage(input []string) bool {
	for _, item := range input {
		if item == "image" {
			return true
		}
	}
	return false
}

// RenderOpenCode merges the gateway provider into an existing opencode.json,
// preserving every other provider, the schema and the selected model.
func RenderOpenCode(existing []byte, baseURL, key string, models []Model) ([]byte, error) {
	document := map[string]any{}
	if len(strings.TrimSpace(string(existing))) > 0 {
		if err := json.Unmarshal(existing, &document); err != nil {
			return nil, fmt.Errorf("opencode.json is not valid JSON: %w", err)
		}
	}
	providers, ok := document["provider"].(map[string]any)
	if !ok {
		providers = map[string]any{}
		document["provider"] = providers
	}
	providers["o2a-v2"] = openCodeProvider(baseURL, key, models)
	data, err := json.MarshalIndent(document, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}
